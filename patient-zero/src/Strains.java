
public class Strains {

    public static int editDistance(String a, String b) {
        int n = a.length(), m = b.length();            // n - длина строки a, m - длина строки b
        int[][] d = new int[n + 1][m + 1];             // таблица на 1 больше по строкам и столбцам (нужна "пустая" строка)
        for (int i = 0; i <= n; i++) d[i][0] = i;      // из i букв в пустую строку: удалить все i букв
        for (int j = 0; j <= m; j++) d[0][j] = j;      // из пустой строки в j букв: вставить все j букв
        for (int i = 1; i <= n; i++) {                 // идём по строкам таблицы (по буквам a)
            for (int j = 1; j <= m; j++) {             // идём по столбцам таблицы (по буквам b)
                // замена: берём диагональ; если буквы равны, +0 (ничего не меняем), иначе +1 (замена стоит 1, не 2)
                int replace = d[i - 1][j - 1] + (a.charAt(i - 1) == b.charAt(j - 1) ? 0 : 1);
                int delete = d[i - 1][j] + 1;          // удаление: берём ячейку сверху и +1
                int insert = d[i][j - 1] + 1;          // вставка: берём ячейку слева и +1
                d[i][j] = Math.min(replace, Math.min(delete, insert)); // выбираем самый дешёвый из трёх способов
            }
        }
        return d[n][m];                                // правый нижний угол = ответ для целых a и b
    }


    public static int lcsLength(String a, String b) {
        int n = a.length(), m = b.length();            // длины строк
        int[][] L = new int[n + 1][m + 1];             // нулевая строка и нулевой столбец остаются 0 (пустая строка -> LCS = 0)
        for (int i = 1; i <= n; i++) {                 // по буквам a
            for (int j = 1; j <= m; j++) {             // по буквам b
                if (a.charAt(i - 1) == b.charAt(j - 1))        // буквы совпали:
                    L[i][j] = L[i - 1][j - 1] + 1;             // диагональ + 1 (берём эту букву в общую последовательность)
                else                                           // буквы разные:
                    L[i][j] = Math.max(L[i - 1][j], L[i][j - 1]); // берём лучшее из "сверху" и "слева" (пропускаем одну букву)
            }
        }
        return L[n][m];                                // правый нижний угол = длина LCS
    }
}
